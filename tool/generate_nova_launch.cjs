// Generates native launch artwork from the supplied NOVA paths, never fonts.
// Requires @resvg/resvg-js on NODE_PATH (no app/runtime dependency).
// PowerShell:
// npm install --prefix .codex/splash-tools --no-audit --no-fund @resvg/resvg-js
// $env:NODE_PATH = "$PWD/.codex/splash-tools/node_modules"
// node tool/generate_nova_launch.cjs
const fs = require('node:fs');
const path = require('node:path');
const { Resvg } = require('@resvg/resvg-js');
const root = path.resolve(__dirname, '..');
const write = (name, value) => {
  const target = path.join(root, name);
  const bytes = Buffer.from(value);
  if (fs.existsSync(target) && fs.readFileSync(target).equals(bytes)) return;
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, bytes);
};
const parts = [
  { file: 'icon_red', x: 100, y: 76, width: 88, sourceWidth: 1041.9 },
  { file: 'wordmark_white', x: 88, y: 187, width: 112, sourceWidth: 2484.6 },
].map(part => {
  const svg = fs.readFileSync(path.join(root, `assets/brand/svg/${part.file}.svg`), 'utf8');
  return {
    ...part,
    scale: part.width / part.sourceWidth,
    paths: [...svg.matchAll(/<path\s+([^>]+)\/>/g)].map(match => ({
      fill: match[1].match(/\bfill="([^"]+)"/)[1],
      data: match[1].match(/\bd="([^"]+)"/)[1],
    })),
  };
});
const artwork = parts.map(part => `  <g transform="translate(${part.x} ${part.y}) scale(${part.scale})">\n${part.paths.map(p => `    <path fill="${p.fill}" fill-rule="evenodd" d="${p.data}"/>`).join('\n')}\n  </g>`).join('\n');
const svg = `<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" width="288" height="288" viewBox="0 0 288 288" role="img" aria-label="NOVA">\n${artwork}\n</svg>\n`;
write('assets/brand/splash/nova_launch.svg', svg);
const groups = parts.map(part => {
  const paths = part.paths.flatMap(p => {
    if (part.file !== 'wordmark_white') return [p];
    // AAPT2 replaces strings over 32767 bytes with STRING_TOO_LARGE, even on
    // successful builds. Split the disjoint letters; keep O's hole with O.
    const contours = p.data.match(/M[^M]+/g);
    if (contours.length !== 5) throw new Error('Review changed wordmark contours.');
    return [contours[0], contours[1], contours.slice(2, 4).join(''), contours[4]]
      .map(data => ({ ...p, data }));
  });
  for (const p of paths) {
    if (Buffer.byteLength(p.data, 'utf8') > 32767) throw new Error('Android path exceeds AAPT2 string limit.');
  }
  return `    <group android:translateX="${part.x}" android:translateY="${part.y}" android:scaleX="${part.scale}" android:scaleY="${part.scale}">\n${paths.map(p => `        <path android:fillColor="${p.fill}" android:fillType="evenOdd" android:pathData="${p.data}"/>`).join('\n')}\n    </group>`;
}).join('\n');
write('android/app/src/main/res/drawable/nova_launch_logo.xml', `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_nova_launch.cjs. Artwork fits Android 12's 192dp safe circle. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="288dp" android:height="288dp" android:viewportWidth="288" android:viewportHeight="288">\n${groups}\n</vector>\n`);
for (const scale of [1, 2, 3]) {
  const png = new Resvg(svg, { fitTo: { mode: 'width', value: 288 * scale } }).render().asPng();
  write(`ios/Runner/Assets.xcassets/LaunchImage.imageset/NovaLaunch@${scale}x.png`, png);
}
// A direct render of the native artwork, useful for reviewing the composition.
const preview = `<svg xmlns="http://www.w3.org/2000/svg" width="390" height="844" viewBox="0 0 390 844"><rect width="390" height="844" fill="#141417"/><g transform="translate(51 278)">${artwork}</g></svg>`;
write('.codex/nova-native-splash-preview.png', new Resvg(preview).render().asPng());
console.log('Generated Android vector, iOS 1x/2x/3x artwork, source SVG and preview.');
